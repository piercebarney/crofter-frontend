	<h2>Fulfillment Policy</h2>

	<h3>Order Availability</h3>

	<ul>
		<li><b>Delivery Orders:</b> Delivered by 8:00 a.m. the next day, provided the order is placed before 8:00 p.m. the previous evening.</li>
		<li><b>Pickup Orders:</b> Available for pickup starting at 8:00 a.m. the next day, provided the order is placed before 8:00 p.m. the previous evening.</li>
		<li>Orders placed after 8:00 p.m. will be available the morning after the next day (i.e., two mornings following placement).</li>
		<li>No orders will be fulfilled or made available on Sundays, Christmas Day, New Year's Day, or Thanksgiving Day.</li>
	</ul>

	<h3>Bulk Orders</h3>

	<ul>
		<li>Bulk orders include large portions of animals (e.g., 1/8 to a whole cow, pig, or other animals) or substantial quantities of any item, which may require additional time based on order size, product availability, and producer timelines. These are typically not available for next-day fulfillment and may take up to a week or more to prepare.</li>
		<li>Bulk orders are available for delivery only and are not eligible for pickup due to their size.</li>
		<li>If a bulk item is included in an order with non-bulk items, the entire order will be fulfilled together—no split deliveries or pickups are available. To receive non-bulk items sooner, place bulk orders separately.</li>
		<li>If a bulk order cannot be fulfilled next day (which is generally the case), customers will be contacted to discuss the situation, coordinate timing, and provide details on what to expect. Availability and handling will vary by circumstances.</li>
	</ul>

	<h3>Delays and Unforeseen Issues</h3>

	<ul>
		<li>Next-day fulfillment (for both delivery and pickup) is our commitment to attempt but is not guaranteed due to potential unforeseen issues, such as supply shortages, producer delays, transportation challenges, or other circumstances.</li>
		<li>In the event of an availability issue preventing next-day fulfillment, the entire order will be delayed. Customers will be promptly contacted to discuss options.</li>
		<li>The delivery fee covers the delivery service itself; we strive for next-day timing but cannot assure it in all cases.</li>
		<li>Customers may request to cancel their order if a delay occurs, and we will process any applicable refunds accordingly.</li>
	</ul>

	<h3>Delivery Requirements</h3>

	<ul>
		<li>Customers must provide a complete and accurate delivery address that is publicly accessible.</li>
		<li>For addresses in restricted areas (e.g., gated communities or access-code-controlled apartment complexes), customers must include clear, detailed access instructions at the time of order placement. These instructions must align with standard delivery windows (5:00 a.m. – 8:00 a.m.).</li>
		<li>Delivery personnel reserve the right to cancel a delivery if, in their professional judgment, conditions present safety hazards. Acts of God or other uncontrollable events will not be considered the customer’s responsibility.</li>
	</ul>

	<h3>Special Instructions</h3>

	<ul>
		<li>Any special requests or instructions must be submitted at the time the order is placed.</li>
		<li>Instructions must be reasonable and must not impose undue burden or inconvenience on delivery operations.</li>
	</ul>

	<h3>Communication</h3>

	<ul>
		<li>Customers will be promptly notified via text message, email, or phone call in the event of any delays, issues, or changes to their order fulfillment.</li>
	</ul>

